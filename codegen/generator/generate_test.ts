Deno.test("staged validation and manifest swap failures preserve the previous snapshot", async () => {
  const temporaryDirectory = await Deno.makeTempDir({
    dir: Deno.cwd(),
    prefix: ".rest-generator-transaction-",
  });
  const root = new URL(`file://${temporaryDirectory}/`);
  const generated = new URL("generated/", root);
  const manifest = new URL("public-names.json", root);
  const previousSource = "export const snapshot = 'previous';\n";
  const nextSource = "export const snapshot = 'next';\n";
  const previousManifest = '{"version":1,"snapshot":"previous"}\n';
  const nextManifest = '{"version":1,"snapshot":"next"}\n';
  await Deno.mkdir(generated);
  await Deno.writeTextFile(new URL("mod.ts", generated), previousSource);
  await Deno.writeTextFile(manifest, previousManifest);

  try {
    const validationFailure = new Error("injected staged type failure");
    assertEquals(
      await captureRejection(
        replaceGeneratedDirectory(generated, new Map([["mod.ts", nextSource]]), {
          validate: () => Promise.reject(validationFailure),
        }),
      ),
      validationFailure,
    );
    assertEquals(await Deno.readTextFile(new URL("mod.ts", generated)), previousSource);

    const swapFailure = new Error("injected manifest swap failure");
    assertEquals(
      await captureRejection(
        replaceGeneratedDirectory(generated, new Map([["mod.ts", nextSource]]), {
          afterGeneratedSwap: () => {
            throw swapFailure;
          },
          manifest: { file: manifest, source: nextManifest },
          validate: () => Promise.resolve(),
        }),
      ),
      swapFailure,
    );
    assertEquals(await Deno.readTextFile(new URL("mod.ts", generated)), previousSource);
    assertEquals(await Deno.readTextFile(manifest), previousManifest);
    const leftovers: string[] = [];
    for await (const entry of Deno.readDir(root)) {
      if (entry.name.startsWith(".generated-") || entry.name.startsWith(".public-names-")) {
        leftovers.push(entry.name);
      }
    }
    assertEquals(leftovers.length, 0);
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

