Deno.test("wire media, no-content, headers, and generated-safe options agree with runtime contract", () => {
  const source = renderProviderClient(
    "fixture",
    fixtureDocument({
      "/media": {
        post: {
          operationId: "mediaPost",
          requestBody: {
            required: true,
            content: {
              "application/octet-stream": {
                schema: {
                  type: "object",
                  properties: { attachment: { type: "string", format: "binary" } },
                },
              },
              "application/vnd.github.object": {
                schema: { type: "object", properties: { entries: { type: "array" } } },
              },
              "text/plain": {
                schema: { type: "object", properties: { value: { type: "string" } } },
              },
              "Application/JSON; charset=utf-8": {
                schema: { type: "object", properties: { value: { type: "string" } } },
              },
            },
          },
          responses: {
            "200": {
              description: "text",
              headers: { "x-next": { schema: { type: "string" } } },
              content: { "text/html": { schema: { type: "object" } } },
            },
            "201": {
              description: "binary",
              content: { "application/zip": { schema: { type: "object" } } },
            },
            "202": {
              description: "reviewed provider JSON media alias",
              content: {
                "application/vnd.github.object": {
                  schema: { type: "object", properties: { entries: { type: "array" } } },
                },
              },
            },
            "203": {
              description: "parameterized mixed-case JSON",
              content: {
                "Application/JSON; charset=utf-8": {
                  schema: { type: "object", properties: { value: { type: "string" } } },
                },
              },
            },
            "204": {
              description: "invalid upstream body must not escape no-content semantics",
              content: { "application/json": { schema: { type: "object" } } },
            },
            default: {
              description: "default multipart response",
              content: { "multipart/related": { schema: { type: "object" } } },
            },
          },
        },
      },
    }),
  );

  assert(source.includes('RestBody<"application/octet-stream", RestBinary>'), "opaque request");
  assert(
    source.includes('RestBody<"application/vnd.github.object", RestBinary>'),
    "response-only JSON media override does not advertise unsupported request serialization",
  );
  assert(
    source.includes(
      'RestBody<"Application/JSON; charset=utf-8", RestJsonValue<RestRequestValue<',
    ),
    "parameterized mixed-case JSON request classification",
  );
  assert(
    source.includes('RestBody<"text/plain", string>'),
    "text wire media incorrectly retained incompatible object schema",
  );
  assert(
    source.includes(
      'RestResponse<200, string, "text/html", true, { readonly "x-next"?: string }>',
    ),
    "text response/header contract",
  );
  assert(
    source.includes('RestResponse<201, globalThis.Blob, "application/zip", true>'),
    "binary response",
  );
  assert(
    source.includes("RestResponse<202, RestJsonValue<") &&
      source.includes('"application/vnd.github.object", true') &&
      source.includes('"application/vnd.github.object":"json"'),
    "reviewed GitHub object media JSON contract",
  );
  assert(
    source.includes('"Application/JSON; charset=utf-8", true') &&
      source.includes('"Application/JSON; charset=utf-8":"json"'),
    "parameterized mixed-case JSON response contract",
  );
  assert(
    source.includes("RestResponse<204, undefined, undefined, true>"),
    "204 no-content response",
  );
  assert(
    source.includes("RestSuccessfulStatus") && source.includes("RestHttpStatus") &&
      source.includes('globalThis.Blob, "multipart/related", true>') &&
      source.includes('globalThis.Blob, "multipart/related", false>'),
    "default multipart response contract",
  );
  assert(source.includes('"decoders":{"text/html":"text"}'), "text decoder metadata");
  assert(
    source.includes('"multipart/related":"binary"'),
    "multipart response decoder metadata",
  );
  assert(source.includes('"headers":["x-next"]'), "response header metadata");
  assert(source.includes("options?: RestGeneratedRequestOptions"), "safe generated options");
});

Deno.test("content-bearing default responses retain runtime 204 and 205 no-content types", () => {
  const source = renderProviderClient(
    "fixture",
    fixtureDocument({
      "/default-only": {
        get: {
          operationId: "defaultOnlyGet",
          responses: {
            default: {
              description: "default JSON",
              headers: { "x-default": { schema: { type: "string" } } },
              content: { "application/json": { schema: { type: "object" } } },
            },
          },
        },
      },
      "/explicit": {
        get: {
          operationId: "explicitGet",
          responses: {
            "204": {
              description: "explicit no content",
              headers: { "x-explicit": { schema: { type: "string" } } },
            },
            default: {
              description: "default JSON",
              headers: { "x-default": { schema: { type: "string" } } },
              content: { "application/json": { schema: { type: "object" } } },
            },
          },
        },
      },
    }),
  );

  const defaultOnly = typeAliasSource(source, "DefaultOnlyGetResponse");
  assert(
    defaultOnly.includes(
      'RestResponse<204, undefined, undefined, true, { readonly "x-default"?: string }>',
    ),
    "default-only 204 runtime branch",
  );
  assert(
    defaultOnly.includes(
      'RestResponse<205, undefined, undefined, true, { readonly "x-default"?: string }>',
    ),
    "default-only 205 runtime branch",
  );
  assert(
    defaultOnly.includes(
      "RestResponse<Exclude<RestSuccessfulStatus, 204 | 205>, RestJsonValue<",
    ) && defaultOnly.includes('"application/json", true') &&
      defaultOnly.includes(
        "RestResponse<Exclude<RestHttpStatus, RestSuccessfulStatus>, RestJsonValue<",
      ) && defaultOnly.includes('"application/json", false'),
    "default success/failure content representations",
  );

  const explicit = typeAliasSource(source, "ExplicitGetResponse");
  assert(
    explicit.includes(
      'RestResponse<204, undefined, undefined, true, { readonly "x-explicit"?: string }>',
    ),
    "explicit 204 response",
  );
  assert(
    !explicit.includes(
      'RestResponse<204, undefined, undefined, true, { readonly "x-default"?: string }>',
    ),
    "default response duplicated explicit 204",
  );
  assert(
    explicit.includes(
      'RestResponse<205, undefined, undefined, true, { readonly "x-default"?: string }>',
    ),
    "missing default-backed 205 response",
  );
});

