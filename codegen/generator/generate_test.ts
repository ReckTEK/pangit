function operation(operationId: string, extra: Record<string, unknown> = {}) {
  return {
    get: {
      operationId,
      responses: {
        "200": {
          description: "ok",
          content: { "application/json": { schema: { type: "object" } } },
        },
      },
      ...extra,
    },
  };
}

function count(value: string, needle: string): number {
  return value.split(needle).length - 1;
}

function typeAliasSource(source: string, name: string): string {
  const value = extractExportedTypeAliases(source, new Set([name])).get(name);
  if (value === undefined) throw new Error(`Missing generated type alias ${name}`);
  return value;
}

function assertThrows(action: () => unknown, message: string): void {
  try {
    action();
  } catch (error) {
    if (error instanceof Error && error.message.includes(message)) return;
    throw error;
  }
  throw new Error(`Expected error containing ${JSON.stringify(message)}`);
}

function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(message);
}

function assertEquals(actual: unknown, expected: unknown): void {
  if (actual !== expected) {
    throw new Error(`Expected ${JSON.stringify(expected)}, received ${JSON.stringify(actual)}`);
  }
}

async function captureRejection(value: Promise<unknown>): Promise<unknown> {
  try {
    await value;
  } catch (error) {
    return error;
  }
  throw new Error("Expected promise to reject");
}
